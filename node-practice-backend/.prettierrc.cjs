/* eslint-env node */
// ===========================================================================
// .prettierrc.cjs — Prettier 代码格式化配置文件
// ===========================================================================
// 使用 .cjs 扩展名而非 .json，目的是支持 JavaScript 注释
// 作用: 统一团队代码风格，避免代码审查中因格式问题产生噪音
// 参考文档: https://prettier.io/docs/en/configuration.html
// ===========================================================================

module.exports = {
  // -------------------------------------------------------------------------
  // 核心格式化规则
  // -------------------------------------------------------------------------

  // printWidth — 每行最大字符数
  // 超过此宽度后 Prettier 会尝试换行。推荐值: 80 或 100
  // 设为 100 能在保持可读性的同时减少不必要的换行
  printWidth: 100,

  // tabWidth — 每个缩进层级使用的空格数
  // 2 个空格是现代前端/Node.js 项目的行业标准缩进
  tabWidth: 2,

  // useTabs — 是否使用制表符(Tab)代替空格缩进
  // false = 使用空格，确保在不同编辑器中显示宽度一致
  useTabs: false,

  // semi — 是否在语句末尾添加分号
  // true 可以减少因 ASI（Automatic Semicolon Insertion，自动分号插入）导致的意外错误
  // 本项目选用 true，与 TypeScript 严格模式更兼容
  semi: false,

  // singleQuote — 是否优先使用单引号代替双引号
  // true 使代码更简洁，减少转义（尤其在包含大量字符串时）
  singleQuote: true,

  // -------------------------------------------------------------------------
  // 对象与数组格式
  // -------------------------------------------------------------------------

  // quoteProps — 对象属性名何时需要加引号
  // "as-needed" = 仅在属性名是非法标识符或含特殊字符时才加引号
  // 其他选项: "consistent"(统一加引号) | "preserve"(保留原样)
  quoteProps: 'as-needed',

  // trailingComma — 多行结构的最后一个元素后是否加尾随逗号
  // "es5" = 在 ES5 有效的位置添加（对象、数组、函数参数等）
  // 尾随逗号的好处: 减少 git diff 噪音，方便后续添加元素
  trailingComma: 'es5',

  // bracketSpacing — 对象字面量的大括号内侧是否保留空格
  // true  => { foo: bar }
  // false => {foo: bar}
  bracketSpacing: true,

  // bracketSameLine — 多行 HTML/JSX 标签的结束符 > 是否放在最后一行末尾
  // false = 放在新行（传统格式，更易于阅读嵌套结构）
  bracketSameLine: false,

  // -------------------------------------------------------------------------
  // 箭头函数与换行
  // -------------------------------------------------------------------------

  // arrowParens — 箭头函数参数是否始终使用括号包裹
  // "always" = 即使只有一个参数也加括号，方便后续添加参数或类型注解
  // 其他选项: "avoid"(单参数省略括号)
  arrowParens: 'always',

  // endOfLine — 换行符风格
  // "lf" = Unix 风格换行符(\n)，确保跨操作系统一致性
  // Windows 用户建议配置 Git: git config --global core.autocrlf true
  endOfLine: 'lf',
}
